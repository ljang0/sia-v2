// Reproduce the model-facing part of the pinned Swift engine. Keep every adapter
// change here rather than gradually rewriting the operating prompt in TypeScript.
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { format, resolveConfig } from 'prettier';

const root = resolve(import.meta.dirname, '..');
const read = (name) => readFile(resolve(root, 'native/notch/upstream', name), 'utf8');
function literal(source, start, end) {
  const body = source.slice(source.indexOf(start) + start.length, source.indexOf(end));
  return body
    .split('\n')
    .map((line) => line.replace(/^ {4,8}/, ''))
    .join('\n')
    .replace(/\\\n\s*/g, '')
    .trim();
}
const invoker = await read('ClaudeCodeInvoker.swift');
let foreground = literal(invoker, 'let base = """', '\n        """\n        if isTopTierModel');
// Detached Claude coding workers and self-replacing the Notch app are different
// transports/lifecycles, not part of the foreground GUI engine being imported.
foreground =
  foreground.slice(0, foreground.indexOf('BACKGROUND CODING WORKERS')) +
  foreground.slice(foreground.indexOf("WHEN APPLESCRIPT CAN'T REACH A UI"));
foreground = foreground
  .replace("living in the MacBook's notch.", 'with results shown in Sia.')
  .replace(
    '\\(screenInfo)',
    'Screen geometry, the native context command and screenshot command are supplied with each request.',
  )
  .replace(
    '\\(skillsSection)',
    'The <skills> block supplied with this request is the current filesystem registry.',
  )
  .replace(
    /`screencapture -x \/tmp\/notch-see.png` then Read\s+that file/,
    'run the supplied screenshot command, then view_image on its PNG',
  )
  .replaceAll(
    '`screencapture -x /tmp/notch-verify.png` and Read it',
    'run the supplied screenshot command and view_image on its PNG',
  )
  .replace(
    /Run `screencapture -x \/tmp\/notch-see.png`, then Read that file — you can view images\. Divide screenshot pixel coordinates by the backing scale factor \(see SCREEN RESOLUTION FACTS above\) to get screen points\./,
    'Run the supplied native screenshot command, then view_image on its PNG. Use its exact image-to-screen transform; the image is already normalized, so do not divide by Retina scale again.',
  )
  .replace(
    /Set every Bash call's `description` to one short\s+present-tense line/,
    'Narrate each exec_command with one short present-tense commentary line',
  );
const consolidation = literal(
  await read('ConsolidationScheduler.swift'),
  'private static let consolidationPrompt = """',
  '\n    """\n}',
);
const brand = (text) =>
  text
    .replaceAll('NotchOutbox', 'SiaOutbox')
    .replaceAll('Notch', 'Sia')
    .replaceAll('the notch', 'Sia')
    .replaceAll('living in the MacBook notch', 'shown in the Sia app');
const output = `// Generated by scripts/port-notch-prompts.mjs from pinned Notch Swift source.\n// Do not edit: adapter transformations belong in the generator.\nexport const NOTCH_FOREGROUND_SOURCE = ${JSON.stringify(brand(foreground))};\nexport const NOTCH_CONSOLIDATION_SOURCE = ${JSON.stringify(brand(consolidation))};\n`;
const destination = resolve(root, 'src/main/notch/prompts.generated.ts');
const formatted = await format(output, {
  ...(await resolveConfig(destination)),
  parser: 'typescript',
});
if (process.argv.includes('--check')) {
  if ((await readFile(destination, 'utf8')) !== formatted)
    throw new Error('Regenerate the pinned Notch prompts with scripts/port-notch-prompts.mjs.');
} else await writeFile(destination, formatted);
